/**
 * The "Aurora" theme: the 1.3.19 skin (aurora, rain, tinted glass panels,
 * glows, the four-colour opening ring), kept as a theme to choose.
 *
 *   node scripts/gerar-tema-aurora.mjs [ref=35f112d3]
 *
 * It reads every sheet that `styles.css` imported at `ref` (1.3.19, the last
 * version before the flat skin) from git, and writes them, in that order, to
 * `packages/ui/src/styles/aurora.gen.css` with every selector scoped to
 * `:root[data-theme="aurora"]`:
 *
 * - The scope adds the same weight (two classes' worth) to every rule, so the
 *   1.3.19 rules keep their order among themselves, and beat the flat skin's
 *   rules wherever both style the same thing.
 * - A selector that starts at the root (`:root`, `html`) gets the scope on the
 *   root itself, and keeps its own `:root` or `html`. One that starts with an attribute (`[data-density=...]`)
 *   is written both ways, on the root and below it: some of those attributes
 *   live on `<html>`, others on elements.
 * - Keyframes are renamed with `-aurora` (and so are the `animation`s that use
 *   them), so the two skins' animations of the same name do not collide.
 *
 * What the flat skin styles and 1.3.19 did not (new markup, like the theme
 * choice in Settings) keeps the flat skin's rules; what the flat skin added
 * to OLD elements is undone by hand in `aurora.css`, measured against 1.3.19
 * in `aurora.test.ts`.
 *
 * Markup the app no longer renders is left out (`RETIRADAS`): its 1.3.19 rules
 * would only be dead weight in the sheet.
 *
 * The output is generated: never edit it. postcss comes with Vite.
 */
import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import postcss from "postcss"

const RAIZ = fileURLToPath(new URL("..", import.meta.url))
const REF = process.argv[2] ?? "35f112d3"
const SAIDA = join(RAIZ, "packages/ui/src/styles/aurora.gen.css")
const ESCOPO = ':root[data-theme="aurora"]'
const SUFIXO = "-aurora"
/** Classes of markup the app no longer renders: a rule whose every selector names one is dropped. */
const RETIRADAS = [/\.frase-do-momento(?![\w-])/, /\.primeiros-passos(?![\w-])|\.primeiros-passos-/]

const git = (caminho) => execFileSync("git", ["show", `${REF}:packages/ui/src/${caminho}`], { cwd: RAIZ, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })

/**
 * One selector, scoped. Returns one or two selectors.
 *
 * Every one gains exactly the scope's weight, so the 1.3.19 order holds: a
 * selector that names the root keeps its own `:root` (or `html`) beside the
 * scope, or `:root .app` would weigh the same as `.app` and lose to a later
 * one, as it did not in 1.3.19.
 */
export function escopar(seletor) {
  const s = seletor.trim()
  if (s.startsWith(":root")) return [ESCOPO + s]
  if (/^html(?![\w-])/.test(s)) return ["html" + ESCOPO + s.slice("html".length)]
  if (s.startsWith("[")) return [ESCOPO + s, `${ESCOPO} ${s}`]
  return [`${ESCOPO} ${s}`]
}

const ficheiros = [...git("styles.css").matchAll(/@import "\.\/(styles\/[A-Za-z]+\.css)"/g)].map((m) => m[1])
const partes = []
const nomesDeAnimacao = new Set()
const raizes = ficheiros.map((caminho) => {
  const raiz = postcss.parse(git(caminho), { from: caminho })
  raiz.walkAtRules("keyframes", (regra) => nomesDeAnimacao.add(regra.params.trim()))
  return { caminho, raiz }
})

const renomear = (valor) =>
  valor.replace(/[A-Za-z_][\w-]*/g, (palavra) => (nomesDeAnimacao.has(palavra) ? palavra + SUFIXO : palavra))

for (const { caminho, raiz } of raizes) {
  raiz.walkComments((comentario) => comentario.remove())
  raiz.walkAtRules("keyframes", (regra) => {
    regra.params = regra.params.trim() + SUFIXO
  })
  raiz.walkRules((regra) => {
    if (regra.parent?.type === "atrule" && /keyframes$/.test(regra.parent.name)) return
    const vivos = regra.selectors.filter((seletor) => !RETIRADAS.some((retirada) => retirada.test(seletor)))
    if (vivos.length === 0) {
      regra.remove()
      return
    }
    regra.selectors = vivos.flatMap(escopar)
  })
  // An at-rule (`@media`, `@supports`) whose every rule was retired goes too.
  raiz.walkAtRules((regra) => {
    if (regra.nodes && regra.nodes.length === 0) regra.remove()
  })
  raiz.walkDecls(/^animation(-name)?$/, (declaracao) => {
    declaracao.value = renomear(declaracao.value)
  })
  partes.push(`/* ${caminho} */\n${raiz.toString().replace(/\n{3,}/g, "\n\n").trim()}\n`)
}

writeFileSync(
  SAIDA,
  `/*
  The "Aurora" theme: the 1.3.19 skin, every rule scoped to ${ESCOPO}.
  GENERATED by \`scripts/gerar-tema-aurora.mjs\` from ${REF}: never edit.
  Hand-made corrections go in \`aurora.css\`.
*/

${partes.join("\n")}`,
  "utf8",
)
console.log(`${ficheiros.length} folhas, ${nomesDeAnimacao.size} animações -> ${SAIDA}`)
